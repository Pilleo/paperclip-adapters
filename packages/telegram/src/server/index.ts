export const TelegramConfigSchema = z.object({
  botToken: z.string().min(1, "Telegram Bot Token is required"),
  allowedUserIds: z.array(z.number().int()).min(1, "At least one allowed user ID is required"),
  defaultChatId: z.union([z.string(), z.number()]).optional(),
  paperclipApiUrl: z.string().url().default("http://127.0.0.1:3100"),
  paperclipApiKey: z.string().optional(),
  paperclipCompanyId: z.string().optional(),
  pollIntervalMs: z.number().int().min(1000).default(3000),
  notifications: z
    .object({
      approvals: z.boolean().default(true),
      clarifications: z.boolean().default(true),
      ciFailures: z.boolean().default(true),
      dailyDigest: z.boolean().default(true),
    })
    .default({
      approvals: true,
      clarifications: true,
      ciFailures: true,
      dailyDigest: true,
    }),
});

export type TelegramConfig = z.infer<typeof TelegramConfigSchema>;

