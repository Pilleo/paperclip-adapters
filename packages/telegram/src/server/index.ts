export async function testEnvironment(
  ctx: AdapterEnvironmentTestContext,
): Promise<AdapterEnvironmentTestResult> {
  const config = (ctx as any).config || (ctx as any).adapterConfig || {};
  const token = typeof config["botToken"] === "string" ? config["botToken"].trim() : process.env["TELEGRAM_BOT_TOKEN"];

  if (!token) {
    return {
      adapterType: "telegram",
      status: "fail",
      testedAt: new Date().toISOString(),
      checks: [
        {
          code: "telegram_token_missing",
          level: "error",
          message: "Telegram Bot Token is not configured",
          detail: "Set botToken in plugin settings or TELEGRAM_BOT_TOKEN in environment",
          hint: "Create a bot with @BotFather on Telegram and copy the API token",
        },
      ],
    };
  }

  try {
    const res = await fetch(`https://api.telegram.org/bot${token}/getMe`);
    if (!res.ok) {
      return {
        adapterType: "telegram",
        status: "fail",
        testedAt: new Date().toISOString(),
        checks: [
          {
            code: "telegram_auth_failed",
            level: "error",
            message: `Telegram API returned status ${res.status}`,
            detail: await res.text(),
            hint: "Check that your Telegram Bot Token is valid and active",
          },
        ],
      };
    }

    const data = (await res.json()) as { ok: boolean; result?: { username?: string; first_name?: string } };
    const botName = data.result?.username ? `@${data.result.username}` : "Telegram Bot";

    return {
      adapterType: "telegram",
      status: "pass",
      testedAt: new Date().toISOString(),
      checks: [
        {
          code: "telegram_bot_connected",
          level: "info",
          message: `Connected successfully to Telegram Bot: ${botName}`,
          detail: null,
          hint: null,
        },
      ],
    };
  } catch (err: any) {
    return {
      adapterType: "telegram",
      status: "fail",
      testedAt: new Date().toISOString(),
      checks: [
        {
          code: "telegram_network_error",
          level: "error",
          message: `Failed to reach Telegram Bot API: ${err.message}`,
          detail: null,
          hint: "Check network connectivity to https://api.telegram.org",
        },
      ],
    };
  }
}

export function createServerAdapter(): ServerAdapterModule {
  return {
    type: "telegram",
    execute: async (_ctx: AdapterExecutionContext): Promise<AdapterExecutionResult> => {
      const plugin = new PaperclipTelegramPlugin();
      await plugin.register();
      return {
        exitCode: 0,
        signal: null,
        timedOut: false,
        summary: "Telegram companion active",
      };
    },
    testEnvironment,
    supportsLocalAgentJwt: true,
    supportsInstructionsBundle: false,
    models: [],
    modelProfiles: [],
    listModels: async () => [],
    listModelProfiles: async () => [],
    agentConfigurationDoc: telegramAgentConfigurationDoc,
    getConfigSchema: () => telegramAdapterConfigSchema,
  };
}

export default createServerAdapter;
